#!/usr/bin/env python3
"""Generate project-scoped Codex custom-agent TOML from agents/*.md.

The Markdown files remain the portable source of truth.  Codex discovers the
generated files under .codex/agents.  Use --check in CI to detect drift.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "agents"
DEST_DIR = ROOT / ".codex" / "agents"


def parse_agent(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n(.*)\Z", text, re.S)
    if not match:
        raise ValueError(f"{path}: missing YAML front matter")
    meta = yaml.safe_load(match.group(1)) or {}
    for key in ("name", "description"):
        if not meta.get(key):
            raise ValueError(f"{path}: missing {key}")
    return meta, match.group(2).strip() + "\n"


def render(path: Path) -> tuple[Path, str]:
    meta, body = parse_agent(path)
    codex_name = str(meta["name"]).replace("-", "_")
    content = (
        "# Generated by bin/sync_codex_agents.py; edit agents/*.md instead.\n"
        f"name = {json.dumps(codex_name, ensure_ascii=False)}\n"
        f"description = {json.dumps(str(meta['description']).strip(), ensure_ascii=False)}\n"
        f"developer_instructions = {json.dumps(body, ensure_ascii=False)}\n"
    )
    return DEST_DIR / f"{codex_name}.toml", content


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    expected = dict(render(path) for path in sorted(SOURCE_DIR.glob("*.md")))
    stale = []
    for path, content in expected.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(path)

    extra = []
    if DEST_DIR.is_dir():
        extra = sorted(set(DEST_DIR.glob("*.toml")) - set(expected))

    if args.check:
        if stale or extra:
            for path in stale:
                print(f"stale or missing: {path.relative_to(ROOT)}")
            for path in extra:
                print(f"unexpected: {path.relative_to(ROOT)}")
            raise SystemExit(1)
        print(f"Codex agents are in sync ({len(expected)} files)")
        return

    DEST_DIR.mkdir(parents=True, exist_ok=True)
    for path in extra:
        path.unlink()
    for path, content in expected.items():
        path.write_text(content, encoding="utf-8")
    print(f"wrote {len(expected)} Codex agents to {DEST_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
